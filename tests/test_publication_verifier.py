def test_crosscheck_fails_on_altered_frozen_config(clone: Path) -> None:
    cfg = clone / "configs/experiments/statarb_historical_etf_wf_v4.yaml"
    text = cfg.read_text("utf-8")
    assert "min_trade_count: 10" in text
    with mutated(cfg, text.replace("min_trade_count: 10", "min_trade_count: 11").encode()):
        r = _cross(clone)
    assert r.returncode == 1


def test_crosscheck_fails_on_tampered_ledger(clone: Path) -> None:
    ledger = clone / "research/experiment-ledger.csv"
    text = ledger.read_text("utf-8")
    bad = text.replace(
        "statarb_hist_etf_wf_v4_holdout_2025", "statarb_hist_etf_wf_v4_holdout_2026", 1
    )
    assert bad != text
    with mutated(ledger, bad.encode()):
        r = _cross(clone)
    assert r.returncode == 1


def test_crosscheck_fails_on_altered_manifest(clone: Path) -> None:
    man = clone / "data/manifests/yf_stat_arb_etfs_daily_2015_2025_v1.json"
    with mutated(man, man.read_bytes().replace(b"DATA FROZEN", b"DATA THAWED")):
        r = _cross(clone)
    assert r.returncode == 1


