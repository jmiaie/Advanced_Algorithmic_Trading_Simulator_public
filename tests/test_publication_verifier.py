"""Fail-closed tests for the stat-arb publication verifier scripts.

The scripts derive their repo root from ``__file__``, so every test runs the
scripts from a throwaway ``git clone`` of the repository placed under pytest's
temp directory (a local clone: no network, committed state only). Mutations are
applied to that clone and always restored; the real repository tree is never
written to. Pure stdlib figures (SVG) are regenerated by the script itself, so
no renderer is involved.
"""

from __future__ import annotations

import contextlib
import hashlib
import importlib.util
import json
import re
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path
from types import ModuleType

import pytest

REPO = Path(__file__).resolve().parents[1]
PACK_REL = Path("publication/stat-arb-study")
SCRIPTS_REL = PACK_REL / "scripts"

pytestmark = pytest.mark.skipif(
    not (REPO / SCRIPTS_REL / "publication_pack.py").exists(),
    reason="publication pack scripts not present",
)


def _is_shallow(repo: Path) -> bool:
    out = subprocess.run(
        ["git", "rev-parse", "--is-shallow-repository"],
        cwd=repo,
        capture_output=True,
        text=True,
    )
    return out.stdout.strip() == "true"


# hashcheck re-reads the freeze commit from git history. CI jobs that check out with the
# default depth of 1 do not have it; the jobs with fetch-depth 0 run these tests.
needs_history = pytest.mark.skipif(
    _is_shallow(REPO), reason="needs full git history (shallow checkout)"
)


def _git(*args: str, cwd: Path) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)


@pytest.fixture(scope="module")
def clone(tmp_path_factory: pytest.TempPathFactory) -> Path:
    dest = tmp_path_factory.mktemp("statarb") / "repo"
    _git("clone", "--quiet", "--no-hardlinks", str(REPO), str(dest), cwd=REPO)
    return dest


def _run(root: Path, script: str, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(root / SCRIPTS_REL / script), *args],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=120,
    )


def _pack(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return _run(root, "publication_pack.py", *args)


def _cross(root: Path) -> subprocess.CompletedProcess[str]:
    return _run(root, "claim_crosscheck.py")


@contextlib.contextmanager
def mutated(path: Path, new: bytes | None) -> Iterator[None]:
    """Replace ``path`` content (or delete it when ``new`` is None); always restore."""
    original = path.read_bytes()
    try:
        if new is None:
            path.unlink()
        else:
            path.write_bytes(new)
        yield
    finally:
        path.write_bytes(original)


def _flip_last_byte(path: Path) -> bytes:
    data = bytearray(path.read_bytes())
    data[-1] ^= 0x01
    return bytes(data)


def _source_artifacts(root: Path) -> list[str]:
    repro = json.loads((root / PACK_REL / "reproducibility.json").read_text("utf-8"))
    return [e["path"] for e in repro["source_artifacts"]]


# --------------------------------------------------------------------------- helpers


def _load_pack(name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, REPO / SCRIPTS_REL / "publication_pack.py")
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_sha256_helpers_known_input() -> None:
    mod = _load_pack("publication_pack_under_test")
    abc = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    assert mod.sha256_bytes(b"abc") == abc == hashlib.sha256(b"abc").hexdigest()


def test_csv_bytes_is_deterministic_lf() -> None:
    mod = _load_pack("publication_pack_under_test2")
    out = mod.csv_bytes(["a", "b"], [{"a": 1, "b": "x"}])
    assert out == b"a,b\n1,x\n"


def test_usage_error_without_mode(clone: Path) -> None:
    assert _pack(clone).returncode == 2
    assert _pack(clone, "bogus").returncode == 2


