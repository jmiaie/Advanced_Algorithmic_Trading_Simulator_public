def test_hashcheck_fails_when_citation_is_bound_to_another_files_hash(clone: Path) -> None:
    # A genuine hash of a *different* file must not satisfy a citation for this path.
    smap = clone / PACK_REL / "RESULT-SOURCE-MAP.md"
    text = smap.read_text("utf-8")
    cites = re.findall(
        r"`((?:results|configs|research|data)/[\w./\-]+\.\w+)`\s*\(sha256 `([0-9a-f]{64})`\)", text
    )
    assert len({d for _, d in cites}) >= 2
    (p1, d1), (_, d2) = cites[0], next(c for c in cites if c[1] != cites[0][1])
    bad = text.replace(f"`{p1}` (sha256 `{d1}`)", f"`{p1}` (sha256 `{d2}`)", 1)
    with mutated(smap, bad.encode()):
        r = _pack(clone, "hashcheck")
    assert r.returncode == 1
    assert "hash-integrity check FAILED" in r.stdout


def test_hashcheck_fails_when_freeze_commit_unreadable(tmp_path: Path, clone: Path) -> None:
    # No git history at all -> the freeze-parent config blob cannot be read: fail closed.
    bare = tmp_path / "nogit"
    subprocess.run(["cp", "-r", str(clone), str(bare)], check=True)
    subprocess.run(["rm", "-rf", str(bare / ".git")], check=True)
    r = _pack(bare, "hashcheck")
    assert r.returncode == 1
    assert "cannot read freeze-parent config" in r.stdout


